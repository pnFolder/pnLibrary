package ru.privatenull.pnlibrary.core.updates

import org.junit.jupiter.api.Assertions.*
import org.junit.jupiter.api.io.TempDir
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.ValueSource
import ru.privatenull.pnlibrary.api.updates.ProductId
import ru.privatenull.pnlibrary.api.updates.UpdateConfigurationBackup
import ru.privatenull.pnlibrary.api.version.ApiVersionRange
import ru.privatenull.pnlibrary.api.version.SemanticVersion
import ru.privatenull.pnlibrary.core.updates.engine.*
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.Paths
import java.util.UUID
import java.util.concurrent.TimeUnit

/** Executed by distribution:verifyUpdaterProcess against the real shaded executable JAR. */
class OfflineUpdaterJarTest {
    @TempDir lateinit var directory: Path

    @ParameterizedTest
    @ValueSource(booleans = [false, true])
    fun `separate updater JVM respects explicit configuration consent during rollback`(restoreConfigurations: Boolean) {
        val plugins = directory.resolve("plugins")
        val data = plugins.resolve("pnLibrary").also(Files::createDirectories)
        val active = plugins.resolve("library.jar").also { Files.write(it, byteArrayOf(1)) }
        val source = directory.resolve("release.jar").also { Files.write(it, byteArrayOf(2, 3)) }
        val api = ApiVersionRange(8, 8)
        val specification = ArtifactSpecification(ProductId.of("pnlibrary"), SemanticVersion.parse("2.0.0"), api, "release.jar")
        val transactions = UpdateTransaction(data.resolve("updates/transactions"), ArtifactVerifier(1024), plugins)
        val plan = UUID.randomUUID()
        val config = data.resolve("config.yml").also { Files.writeString(it, "version: 1") }
        val unrelated = data.resolve("unrelated.yml").also { Files.writeString(it, "keep") }
        val snapshots = ConfigurationSnapshots(data.resolve("updates/configurations"), plugins)
        val snapshot = snapshots.capture(plan, mapOf(ProductId.of("pnlibrary") to UpdateConfigurationBackup(data, listOf("config.yml", "optional.yml"))))
        val saved = transactions.prepareForRestart(listOf(TransactionArtifact(specification, source,
            plugins.resolve("update/library.jar"), active, "1.0.0", api, active)), planId = plan, targetApi = 8, configurationSnapshot = snapshot)

        UpdateInstallationLock.acquire(data).use { assertNotEquals(0, runUpdater(data)) }
        assertArrayEquals(byteArrayOf(1), Files.readAllBytes(active))
        assertEquals(0, runUpdater(data))
        assertArrayEquals(byteArrayOf(2, 3), Files.readAllBytes(active))
        assertEquals("version: 1", Files.readString(config))
        Files.writeString(config, "version: 2")
        Files.writeString(data.resolve("optional.yml"), "generated by version 2")
        assertEquals(0, runUpdater(data))
        transactions.completeHealth(saved.journal, true)
        transactions.rollback(saved.journal, restoreConfigurations)
        assertEquals(0, runUpdater(data))
        assertArrayEquals(byteArrayOf(1), Files.readAllBytes(active))
        assertEquals(if (restoreConfigurations) "version: 1" else "version: 2", Files.readString(config))
        assertEquals(!restoreConfigurations, Files.exists(data.resolve("optional.yml")))
        assertEquals("keep", Files.readString(unrelated))
        assertEquals(0, runUpdater(data))
    }

    private fun runUpdater(data: Path): Int {
        val executable = Paths.get(System.getProperty("java.home"), "bin", "java.exe").let {
            if (Files.exists(it)) it else it.resolveSibling("java")
        }
        val jar = requireNotNull(System.getProperty("pnlibrary.updater.jar")) { "run distribution:verifyUpdaterProcess" }
        val process = ProcessBuilder(executable.toString(), "-jar", jar, "--server-stopped", data.toString())
            .redirectErrorStream(true).start()
        if (!process.waitFor(30, TimeUnit.SECONDS)) {
            process.destroyForcibly().waitFor()
            fail<Unit>("Updater process exceeded its test timeout")
        }
        val output = process.inputStream.bufferedReader().use { it.readText() }
        if (process.exitValue() != 0 && !output.contains("Cannot acquire update lock")) fail<Unit>(output)
        return process.exitValue()
    }
}
