package org.pnfolder.pnlibrary.updates.install;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.fail;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Arrays;
import java.util.Collections;
import java.util.UUID;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.pnfolder.pnlibrary.api.updates.backup.UpdateConfigurationBackup;
import org.pnfolder.pnlibrary.api.updates.product.ProductId;
import org.pnfolder.pnlibrary.api.version.ApiVersionRange;
import org.pnfolder.pnlibrary.api.version.SemanticVersion;
import org.pnfolder.pnlibrary.updates.engine.net.ArtifactSpecification;
import org.pnfolder.pnlibrary.updates.engine.net.ArtifactVerifier;
import org.pnfolder.pnlibrary.updates.engine.transaction.TransactionArtifact;
import org.pnfolder.pnlibrary.updates.engine.transaction.TransactionResult;
import org.pnfolder.pnlibrary.updates.engine.transaction.UpdateTransaction;
import org.pnfolder.pnlibrary.updates.history.ConfigurationSnapshots;
import org.pnfolder.pnlibrary.updates.paths.LibraryPaths;
import org.pnfolder.pnlibrary.updates.service.UpdateInstallationLock;

/** Executed by distribution:verifyUpdaterProcess against the real shaded executable JAR. */
class OfflineUpdaterJarTest {
    @TempDir
    Path directory;

    @ParameterizedTest
    @ValueSource(booleans = {false, true})
    void separateUpdaterJvmRespectsExplicitConfigurationConsentDuringRollback(boolean restoreConfigurations) throws Exception {
        Path plugins = directory.resolve("plugins");
        Path data = plugins.resolve("pnLibrary");
        Files.createDirectories(data);
        Path active = plugins.resolve("library.jar");
        Files.write(active, new byte[] {1});
        Path source = directory.resolve("release.jar");
        Files.write(source, new byte[] {2, 3});
        ApiVersionRange api = new ApiVersionRange(8, 8);
        ArtifactSpecification specification = new ArtifactSpecification(ProductId.of("pnlibrary"),
            SemanticVersion.parse("2.0.0"), api, "release.jar");
        UpdateTransaction transactions = new UpdateTransaction(new LibraryPaths(data).getTransactions(),
            new ArtifactVerifier(1024), plugins);
        UUID plan = UUID.randomUUID();
        Path config = data.resolve("config.yml");
        write(config, "version: 1");
        Path unrelated = data.resolve("unrelated.yml");
        write(unrelated, "keep");
        ConfigurationSnapshots snapshots = new ConfigurationSnapshots(new LibraryPaths(data).getConfigurations(), plugins);
        UUID snapshot = snapshots.capture(plan, Collections.singletonMap(ProductId.of("pnlibrary"),
            new UpdateConfigurationBackup(data, Arrays.asList("config.yml", "optional.yml"))));
        TransactionResult saved = transactions.prepareForRestart(Collections.singletonList(new TransactionArtifact(
            specification, source, plugins.resolve("update/library.jar"), active, "1.0.0", api, active)), plan, 8, snapshot);

        try (UpdateInstallationLock lock = UpdateInstallationLock.acquire(new LibraryPaths(data))) {
            assertNotEquals(0, runUpdater(data));
        }
        assertArrayEquals(new byte[] {1}, Files.readAllBytes(active));
        assertEquals(0, runUpdater(data));
        assertArrayEquals(new byte[] {2, 3}, Files.readAllBytes(active));
        assertEquals("version: 1", read(config));
        write(config, "version: 2");
        write(data.resolve("optional.yml"), "generated by version 2");
        assertEquals(0, runUpdater(data));
        transactions.completeHealth(saved.getJournal(), true);
        transactions.rollback(saved.getJournal(), restoreConfigurations);
        assertEquals(0, runUpdater(data));
        assertArrayEquals(new byte[] {1}, Files.readAllBytes(active));
        assertEquals(restoreConfigurations ? "version: 1" : "version: 2", read(config));
        assertEquals(!restoreConfigurations, Files.exists(data.resolve("optional.yml")));
        assertEquals("keep", read(unrelated));
        assertEquals(0, runUpdater(data));
    }

    private static void write(Path file, String text) throws IOException {
        Files.write(file, text.getBytes(StandardCharsets.UTF_8));
    }

    private static String read(Path file) throws IOException {
        return new String(Files.readAllBytes(file), StandardCharsets.UTF_8);
    }

    private int runUpdater(Path data) throws Exception {
        Path executable = Paths.get(System.getProperty("java.home"), "bin", "java.exe");
        if (!Files.exists(executable)) {
            executable = executable.resolveSibling("java");
        }
        String jar = System.getProperty("pnlibrary.updater.jar");
        if (jar == null) {
            throw new IllegalArgumentException("run distribution:verifyUpdaterProcess");
        }
        Process process = new ProcessBuilder(executable.toString(), "-jar", jar, "--server-stopped", data.toString())
            .redirectErrorStream(true).start();
        if (!process.waitFor(30, TimeUnit.SECONDS)) {
            process.destroyForcibly().waitFor();
            fail("Updater process exceeded its test timeout");
        }
        String output = readAll(process.getInputStream());
        if (process.exitValue() != 0 && !output.contains("Cannot acquire update lock")) {
            fail(output);
        }
        return process.exitValue();
    }

    private static String readAll(InputStream input) throws IOException {
        ByteArrayOutputStream output = new ByteArrayOutputStream();
        byte[] buffer = new byte[8192];
        for (int count = input.read(buffer); count >= 0; count = input.read(buffer)) {
            output.write(buffer, 0, count);
        }
        input.close();
        return new String(output.toByteArray(), StandardCharsets.UTF_8);
    }
}
