// pnlibrary-loader — Java-only helper that downloads the runtime libraries a light JAR leaves out.
// Nothing here may need Kotlin: it runs before Kotlin is on the classpath.
import java.security.MessageDigest
import java.util.Base64
import org.gradle.api.artifacts.ResolvedArtifact

plugins {
    `java-library`
}

dependencies {
    api(libs.libby.core)
    api(project(":modules:console"))

    testImplementation(libs.junit.jupiter)
    testImplementation(libs.mockito.core)
    testRuntimeOnly(libs.junit.launcher)
}

// RuntimeLibraries.java lists, per platform, every library the light JAR leaves out: group, name, version and the
// SHA-256 of the exact file Gradle resolved. It is generated, so the list always follows the version catalog.
// The servers already bring Gson, and Velocity brings Adventure itself.
//
// Where a library is downloaded from is set in two places:
//   - LibrarySettings.DEFAULT: every library on every platform (own mirrors, Maven Central, fallback mirrors);
//   - lib(dependency, "https://...") below: that library and everything it pulls in, tried before the common ones.
// Whichever repository answers, the file must match the recorded SHA-256, so a mirror cannot swap a library.
class Root(val dependency: Provider<MinimalExternalModuleDependency>, val repositories: List<String>)

fun lib(dependency: Provider<MinimalExternalModuleDependency>, vararg repositories: String) =
    Root(dependency, repositories.toList())

val platformLibraries: Map<String, List<Root>> = mapOf(
    "BUKKIT" to listOf(lib(libs.kotlin.stdlib), lib(libs.adventure.legacy), lib(libs.adventure.platform.bukkit)),
    "BUNGEE" to listOf(lib(libs.kotlin.stdlib), lib(libs.adventure.legacy)),
    "VELOCITY" to listOf(lib(libs.kotlin.stdlib)),
)
val skippedGroups = listOf("com.google")

val generatedSources = layout.buildDirectory.dir("generated/runtimeLibraries")

// ProductInfo.java carries the links the failure card shows, taken from gradle.properties like everything else.
val productName = rootProject.property("pnlibrary.name").toString()
val supportUrl = rootProject.property("pnlibrary.support-url").toString()
val releasesUrl = "https://github.com/" + rootProject.property("pnlibrary.repository") + "/releases/latest"

val generateRuntimeLibraries by tasks.registering {
    platformLibraries.values.flatten().forEach {
        inputs.property(it.dependency.get().toString(), it.dependency.get().version.toString() + it.repositories)
    }
    inputs.property("productName", productName)
    inputs.property("supportUrl", supportUrl)
    inputs.property("releasesUrl", releasesUrl)
    outputs.dir(generatedSources)
    doLast {
        val info = generatedSources.get().file("org/pnfolder/pnlibrary/loader/ProductInfo.java").asFile
        info.parentFile.mkdirs()
        info.writeText(
            "package org.pnfolder.pnlibrary.loader;\n\n" +
                "/** Generated by platforms/loader/build.gradle.kts from gradle.properties. Do not edit. */\n" +
                "final class ProductInfo {\n" +
                "    static final String NAME = \"$productName\";\n" +
                "    static final String SUPPORT_URL = \"$supportUrl\";\n" +
                "    static final String RELEASES_URL = \"$releasesUrl\";\n\n" +
                "    private ProductInfo() {\n    }\n}\n",
        )
        val fields = platformLibraries.map { (platform, roots) ->
            // A library reached from several roots keeps the repositories of all of them.
            val found = linkedMapOf<String, Pair<ResolvedArtifact, MutableList<String>>>()
            roots.forEach { root ->
                val config = configurations.detachedConfiguration(dependencies.create(root.dependency.get()))
                config.resolvedConfiguration.resolvedArtifacts
                    .filter { artifact -> skippedGroups.none { artifact.moduleVersion.id.group.startsWith(it) } }
                    .forEach { artifact ->
                        val id = artifact.moduleVersion.id
                        found.getOrPut(id.toString()) { artifact to mutableListOf() }.second
                            .addAll(root.repositories)
                    }
            }
            val entries = found.toSortedMap().values.joinToString(",\n") { (artifact, repositories) ->
                val id = artifact.moduleVersion.id
                val checksum = Base64.getEncoder()
                    .encodeToString(MessageDigest.getInstance("SHA-256").digest(artifact.file.readBytes()))
                val extra = repositories.distinct().joinToString("") { ", \"$it\"" }
                "        library(\"${id.group}\", \"${id.name}\", \"${id.version}\", \"$checksum\"$extra)"
            }
            "    /** Libraries the light JAR needs on $platform. */\n" +
                "    public static final Library[] $platform = {\n$entries\n    };"
        }
        val file = generatedSources.get().file("org/pnfolder/pnlibrary/loader/RuntimeLibraries.java").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package org.pnfolder.pnlibrary.loader;\n\n" +
                "import net.byteflux.libby.Library;\n\n" +
                "/** Generated by platforms/loader/build.gradle.kts from the version catalog. Do not edit. */\n" +
                "public final class RuntimeLibraries {\n" +
                fields.joinToString("\n\n") + "\n\n" +
                "    private RuntimeLibraries() {\n    }\n\n" +
                "    private static Library library(String group, String name, String version, String checksum,\n" +
                "                                   String... repositories) {\n" +
                "        Library.Builder builder = Library.builder().groupId(group).artifactId(name).version(version)\n" +
                "                .checksum(checksum);\n" +
                "        for (String repository : repositories) {\n" +
                "            builder.repository(repository);\n" +
                "        }\n" +
                "        return builder.build();\n" +
                "    }\n}\n",
        )
    }
}
sourceSets.named("main") { java.srcDir(generatedSources) }
tasks.named("compileJava") { dependsOn(generateRuntimeLibraries) }
tasks.matching { it.name == "sourcesJar" }.configureEach { dependsOn(generateRuntimeLibraries) }

// This module has no Kotlin plugin, so the shared test setup does not reach it.
tasks.test { useJUnitPlatform() }
